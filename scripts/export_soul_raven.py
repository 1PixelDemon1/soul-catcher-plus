"""Export the original Blockbench raven to the native Forge 1.16.5 renderer.

Run from any directory with Python 3. Uses only the standard library. Materials
are flat swatches, one material per cuboid.
Animation remains hand-authored in SoulRavenModel, independently of geometry.
"""
from pathlib import Path
import base64
import json
import math
import struct
import zlib

ROOT = Path(__file__).resolve().parent.parent
MODEL = ROOT / 'modeling/legendary-raven/legendary_raven.bbmodel'
OUTPUT = ROOT / 'src/main/java/dev/soulcatcherplus/client/model/SoulRavenGeometry.java'
TEXTURES = ROOT / 'src/main/resources/assets/soulcatcherplus/textures/entity'

def material_color(texture):
    """Read the first RGB pixel of the model's flat swatch instead of duplicating its palette."""
    data = base64.b64decode(texture['source'].split(',', 1)[1])
    if data[:8] != b'\x89PNG\r\n\x1a\n' or data[24] != 8 or data[25] not in (2, 6):
        raise ValueError('Raven materials must be flat 8-bit RGB/RGBA PNG swatches')
    compressed = bytearray()
    offset = 8
    while offset < len(data):
        size = struct.unpack_from('>I', data, offset)[0]
        if data[offset + 4:offset + 8] == b'IDAT':
            compressed.extend(data[offset + 8:offset + 8 + size])
        offset += size + 12
    # At the first pixel all PNG filter predictors are zero; these are the original RGB bytes.
    return zlib.decompress(compressed)[1:4]


def write_png(path, colors, eye_tiles, eyes_only):
    def chunk(tag, data):
        return (struct.pack('>I', len(data)) + tag + data
                + struct.pack('>I', zlib.crc32(tag + data) & 0xffffffff))
    rows = []
    for y in range(64):
        row = bytearray([0])
        for x in range(128):
            tile = y // 32 * 4 + x // 32
            alpha = 255 if tile < len(colors) and (not eyes_only or tile in eye_tiles) else 0
            # The native eyes layer uses additive blending: transparent texels
            # must also have black RGB, otherwise the entire bird would glow.
            rgb = colors[tile] if alpha else bytes(3)
            row.extend(rgb + bytes([alpha]))
        rows.append(row)
    path.write_bytes(b'\x89PNG\r\n\x1a\n'
                     + chunk(b'IHDR', struct.pack('>IIBBBBB', 128, 64, 8, 6, 0, 0, 0))
                     + chunk(b'IDAT', zlib.compress(b''.join(rows))) + chunk(b'IEND', b''))


def number(value):
    return f'{value:.6f}'.rstrip('0').rstrip('.') + 'f'


def main():
    model = json.loads(MODEL.read_text(encoding='utf-8'))
    cubes = {c['uuid']: c for c in model['elements']}
    groups = {g['uuid']: g for g in model['groups']}
    materials = {t['uuid']: i for i, t in enumerate(model['textures'])}
    if len(materials) > 8:
        raise ValueError('The raven material atlas has room for eight swatches')
    colors = [material_color(texture) for texture in model['textures']]
    eye_tiles = {i for i, texture in enumerate(model['textures']) if texture['name'] in ('eye', 'eye_glint')}
    lines = [
        '// SPDX-License-Identifier: MIT',
        '// Generated by scripts/export_soul_raven.py from legendary_raven.bbmodel.',
        '// Edit the Blockbench source, then regenerate; do not hand-edit geometry.',
        'package dev.soulcatcherplus.client.model;', '',
        'import net.minecraft.client.renderer.model.ModelRenderer;',
        'import java.util.LinkedHashMap;', 'import java.util.Map;', '',
        'final class SoulRavenGeometry {',
        '    private SoulRavenGeometry() {}', '',
        '    static Map<String, ModelRenderer> create(SoulRavenModel model) {',
        '        Map<String, ModelRenderer> bones = new LinkedHashMap<>();',
    ]

    def walk(group, parent=None, parent_origin=(0, 0, 0)):
        definition = groups[group['uuid']]
        name, origin = definition['name'], definition.get('origin', [0, 0, 0])
        delta = [origin[i] - parent_origin[i] for i in range(3)]
        delta[1] *= -1
        if parent is None:
            delta[1] += 24
        lines.append(f'        ModelRenderer {name} = bone(model, bones, "{name}", '
                     + ', '.join(map(number, delta)) + ');')
        if parent:
            lines.append(f'        {parent}.addChild({name});')
        for child in group['children']:
            if isinstance(child, dict):
                walk(child, name, origin)
                continue
            cube = cubes[child]
            pivot = cube.get('origin', [0, 0, 0])
            position = [pivot[0]-origin[0], origin[1]-pivot[1], pivot[2]-origin[2]]
            lo, hi = cube['from'], cube['to']
            bounds = [lo[0]-pivot[0], pivot[1]-hi[1], lo[2]-pivot[2]]
            bounds += [hi[i]-lo[i] for i in range(3)]
            rotation = cube.get('rotation', [0, 0, 0])
            rotation = [math.radians(rotation[i]) * (-1 if i != 1 else 1) for i in range(3)]
            tile = materials[cube['faces']['north']['texture']]
            values = [tile % 4 * 32, tile // 4 * 32]
            lines.append(f'        // {cube["name"]}')
            lines.append(f'        cube(model, {name}, {values[0]}, {values[1]}, '
                         + ', '.join(map(number, position + bounds + rotation)) + ');')

    for group in model['outliner']:
        walk(group)
    lines += [
        '        return bones;', '    }', '',
        '    private static ModelRenderer bone(SoulRavenModel model, Map<String, ModelRenderer> bones,',
        '            String name, float x, float y, float z) {',
        '        ModelRenderer bone = new ModelRenderer(model);',
        '        bone.setPos(x, y, z);', '        bones.put(name, bone);',
        '        return bone;', '    }', '',
        '    private static void cube(SoulRavenModel model, ModelRenderer parent, int u, int v,',
        '            float px, float py, float pz, float x, float y, float z,',
        '            float width, float height, float depth, float rx, float ry, float rz) {',
        '        ModelRenderer cube = new ModelRenderer(model, u, v);',
        '        cube.setPos(px, py, pz);',
        '        cube.xRot = rx;', '        cube.yRot = ry;', '        cube.zRot = rz;',
        '        cube.addBox(x, y, z, width, height, depth);',
        '        parent.addChild(cube);', '    }', '}', '',
    ]
    OUTPUT.parent.mkdir(parents=True, exist_ok=True)
    OUTPUT.write_text('\n'.join(lines), encoding='utf-8')
    TEXTURES.mkdir(parents=True, exist_ok=True)
    write_png(TEXTURES / 'soul_raven.png', colors, eye_tiles, False)
    write_png(TEXTURES / 'soul_raven_eyes.png', colors, eye_tiles, True)
    print(f'Exported {len(cubes)} cuboids and two 128x64 material atlases.')


if __name__ == '__main__':
    main()
