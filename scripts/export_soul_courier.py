"""Export the approved Courier cuboids/UVs unchanged; vanilla textures stay vanilla resources."""
import json
import shutil
from pathlib import Path

ROOT = Path(__file__).resolve().parent.parent
SOURCE = ROOT / 'modeling/soul-courier/soul_courier.bbmodel'
OUTPUT = ROOT / 'src/main/java/dev/soulcatcherplus/client/model/SoulCourierGeometry.java'
TEXTURES = ROOT / 'src/main/resources/assets/soulcatcherplus/textures/entity/soul_courier'
MATERIALS = {'skeleton': 'SKELETON', 'ender_chest': 'CHEST', 'cloak': 'CLOAK',
             'cloak_shadow': 'CLOAK', 'cloak_edge': 'CLOAK', 'strap': 'STRAP', 'soul': 'SOUL'}
FACES = ('north', 'south', 'west', 'east', 'down', 'up')


def number(value):
    return f'{value:.6f}'.rstrip('0').rstrip('.') + 'f'


def main():
    model = json.loads(SOURCE.read_text(encoding='utf-8'))
    groups = {group['uuid']: group for group in model['groups']}
    cubes = {cube['uuid']: cube for cube in model['elements']}
    textures = {texture['uuid']: texture for texture in model['textures']}
    lines = ['// SPDX-License-Identifier: MIT', '// Generated by scripts/export_soul_courier.py; edit the Blockbench source.',
             'package dev.soulcatcherplus.client.model;', '', 'import java.util.LinkedHashMap;', 'import java.util.Map;',
             'import dev.soulcatcherplus.client.model.SoulCourierModel.Material;',
             'import dev.soulcatcherplus.client.model.SoulCourierModel.Part;', '',
             'final class SoulCourierGeometry {', '    private SoulCourierGeometry() {}', '',
             '    static Map<String, Part> create() {', '        Map<String, Part> parts = new LinkedHashMap<>();']

    def part(name, origin, rotation, parent, parent_origin):
        values = [origin[i] - parent_origin[i] for i in range(3)] + rotation
        lines.append(f'        Part {name} = new Part(' + ', '.join(map(number, values)) + ');')
        if parent:
            lines.append(f'        {parent}.children.add({name});')

    def walk(node, parent=None, parent_origin=(0, 0, 0)):
        group = groups[node['uuid']]
        name, origin = group['name'], group['origin']
        part(name, origin, group.get('rotation', [0, 0, 0]), parent, parent_origin)
        lines.append(f'        parts.put("{name}", {name});')
        for child in node['children']:
            if isinstance(child, dict):
                walk(child, name, origin)
                continue
            cube = cubes[child]
            materials = {MATERIALS[textures[face['texture']]['name']] for face in cube['faces'].values()}
            if len(materials) != 1:
                raise ValueError('Courier cubes must use one material per cube')
            owner, pivot = name, origin
            rotation = cube.get('rotation', [0, 0, 0])
            if any(rotation):
                owner, pivot = 'cube_' + cube['name'], cube['origin']
                part(owner, pivot, rotation, name, origin)
            bounds = [cube[edge][i] - pivot[i] for edge in ('from', 'to') for i in range(3)]
            uv = []
            for face_name in FACES:
                face = cube['faces'][face_name]
                if face.get('rotation', 0):
                    raise ValueError('Rotated face UVs need an explicit export rule')
                texture = textures[face['texture']]
                # Embedded texture dimensions, not the generic project's default resolution.
                width, height = texture['uv_width'], texture['uv_height']
                uv.extend(value / (width if i % 2 == 0 else height) for i, value in enumerate(face['uv']))
            lines.extend([f'        // {cube["name"]}',
                      f'        {owner}.cube(Material.{materials.pop()}, ' + ', '.join(map(number, bounds))
                      + ', new float[] {' + ', '.join(map(number, uv)) + '});'])

    walk(model['outliner'][0])
    lines += ['        return parts;', '    }', '}', '']
    OUTPUT.write_text('\n'.join(lines), encoding='utf-8')
    TEXTURES.mkdir(parents=True, exist_ok=True)
    for name in ('cloak', 'strap', 'soul'):
        shutil.copyfile(SOURCE.parent / 'textures' / (name + '.png'), TEXTURES / (name + '.png'))
    print(f'Exported {len(cubes)} Courier cuboids, face UVs and three custom textures.')


if __name__ == '__main__':
    main()
