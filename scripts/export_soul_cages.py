"""Export the approved standard cage and supreme bone reliquary (stdlib only)."""
from pathlib import Path
import base64
import json
import struct
import zlib

ROOT = Path(__file__).resolve().parent.parent
SOURCE = ROOT / 'modeling/iron-soul-cage/iron_soul_cage.bbmodel'
SUPREME_SOURCE = ROOT / 'modeling/supreme-soul-cage/supreme_soul_cage.bbmodel'
OUTPUT = ROOT / 'src/main/java/dev/soulcatcherplus/client/model/SoulCageGeometry.java'


def number(value):
    return f'{value:.6f}'.rstrip('0').rstrip('.') + 'f'


def main():
    model = json.loads(SOURCE.read_text(encoding='utf-8'))
    supreme = json.loads(SUPREME_SOURCE.read_text(encoding='utf-8'))
    def material(texture):
        png = base64.b64decode(texture['source'].split(',', 1)[1])
        offset, compressed = 8, bytearray()
        while offset < len(png):
            size = struct.unpack_from('>I', png, offset)[0]
            if png[offset+4:offset+8] == b'IDAT':
                compressed.extend(png[offset+8:offset+8+size])
            offset += size + 12
        pixels = zlib.decompress(compressed)
        if pixels[0] != 0:
            raise ValueError('Expected an unfiltered flat RGBA material.')
        return pixels[1:5].hex().upper()
    colors = {t['uuid']: material(t) for t in model['textures']}
    roles = {'iron_shadow': 'shadow', 'iron': 'metal', 'iron_highlight': 'highlight'}
    face_colors = {t['uuid']: roles.get(t['name'], '0x' + colors[t['uuid']]) for t in model['textures']}
    materials = json.loads((ROOT / 'art/soul-cages/animated/sprites.json').read_text(encoding='utf-8'))['materials']
    iron = {t['name']: colors[t['uuid']] for t in model['textures']}
    groups = {g['uuid']: g for g in model['groups']}
    cubes = {c['uuid']: c for c in model['elements']}
    lines = ['// SPDX-License-Identifier: MIT',
             '// Generated by scripts/export_soul_cages.py; edit the Blockbench source or cage palette.',
             'package dev.soulcatcherplus.client.model;', '',
             'final class SoulCageGeometry {',
             '    private SoulCageGeometry() {}', '',
             '    static SoulCageModel.Part create(SoulCageModel.Material material) {',
             '        switch (material) {']
    for name in ('iron', 'diamond', 'netherite'):
        palette = ([iron['iron_shadow'], iron['iron'], iron['iron_highlight']] if name == 'iron'
                   else [materials[name][key] for key in ('o', 'm', 'h')])
        lines.append(f'            case {name.upper()}: return create('
                     + ', '.join('0x' + color for color in palette) + ');')
    lines += ['            case SUPREME: return createSupreme();',
              '            default: throw new IllegalArgumentException("Unsupported cage material: " + material);',
              '        }', '    }', '',
              '    private static SoulCageModel.Part create(int shadow, int metal, int highlight) {']

    def walk(node, parent=None, parent_origin=(0, 0, 0)):
        group = groups[node['uuid']]
        name, origin = group['name'], group['origin']
        pivot = [origin[i] - parent_origin[i] for i in range(3)]
        lines.append(f'        SoulCageModel.Part {name} = new SoulCageModel.Part("{name}", '
                     + ', '.join(map(number, pivot)) + ');')
        if parent:
            lines.append(f'        {parent}.children.add({name});')
        for child in node['children']:
            if isinstance(child, dict):
                walk(child, name, origin)
                continue
            cube = cubes[child]
            if any(cube.get('rotation', [0, 0, 0])):
                raise ValueError('This cage exporter expects axis-aligned cuboids.')
            bounds = [cube[edge][i] - origin[i] for edge in ('from', 'to') for i in range(3)]
            rgba = [face_colors[cube['faces'][face]['texture']] for face in
                    ('north', 'south', 'west', 'east', 'down', 'up')]
            # Crown stars share the full-bright soul pass, but their bone does not orbit.
            surface = 'GLASS' if name == 'glass' else 'SOUL' if name.startswith('soul_') or name == 'star' else 'FRAME'
            lines.append(f'        // {cube["name"]}')
            lines.append(f'        {name}.cube(SoulCageModel.Surface.{surface}, '
                         + ', '.join(map(number, bounds)) + ', '
                         + ', '.join(rgba) + ');')

    walk(model['outliner'][0])
    lines += ['        return root;', '    }', '',
              '    private static SoulCageModel.Part createSupreme() {']
    # Reuse the same hierarchy exporter for the separately authored supreme mesh.
    groups = {g['uuid']: g for g in supreme['groups']}
    cubes = {c['uuid']: c for c in supreme['elements']}
    face_colors = {t['uuid']: '0x' + material(t) for t in supreme['textures']}
    walk(supreme['outliner'][0])
    lines += ['        return root;', '    }', '}', '']
    OUTPUT.write_text('\n'.join(lines), encoding='utf-8')
    # A uniform white material lets the mesh retain each face's original RGBA.
    def chunk(tag, data):
        return struct.pack('>I', len(data)) + tag + data + struct.pack('>I', zlib.crc32(tag + data) & 0xffffffff)
    texture = ROOT / 'src/main/resources/assets/soulcatcherplus/textures/item/cage_material.png'
    texture.write_bytes(b'\x89PNG\r\n\x1a\n'
                       + chunk(b'IHDR', struct.pack('>IIBBBBB', 8, 8, 8, 6, 0, 0, 0))
                       + chunk(b'IDAT', zlib.compress((b'\0' + b'\xff' * 32) * 8)) + chunk(b'IEND', b''))
    print(f'Exported standard cage ({len(model["elements"])} cuboids, three palettes) '
          f'and supreme cage ({len(supreme["elements"])} cuboids); inventory textures unchanged.')


if __name__ == '__main__':
    main()
