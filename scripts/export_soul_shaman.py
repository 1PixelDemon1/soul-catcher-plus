"""Export the cuboid-only Shaman with exact face materials/UVs and embedded PNGs."""
import base64
import json
import re
from pathlib import Path

ROOT=Path(__file__).resolve().parent.parent
SOURCE=ROOT/'modeling/soul-shaman-cuboid/soul_shaman.bbmodel'
OUTPUT=ROOT/'src/main/java/dev/soulcatcherplus/client/model/SoulShamanGeometry.java'
TEXTURES=ROOT/'src/main/resources/assets/soulcatcherplus/textures/entity/soul_shaman'
FACES=('north','south','west','east','down','up')


def number(value):
    return f'{value:.6f}'.rstrip('0').rstrip('.')+'f'


def identifier(name):
    # Blockbench permits punctuation in names (for example skirt_side_-1).
    return 'part_'+re.sub(r'[^a-zA-Z0-9_]', '_', name)


def main():
    model=json.loads(SOURCE.read_text(encoding='utf-8'))
    groups={g['uuid']:g for g in model['groups']}
    cubes={c['uuid']:c for c in model['elements']}
    textures={t['uuid']:t for t in model['textures']}
    if any(c.get('type')!='cube' for c in cubes.values()):
        raise ValueError('Soul Shaman runtime source must contain cuboids only')
    lines=['// SPDX-License-Identifier: MIT',
           '// Generated by scripts/export_soul_shaman.py; edit the cuboid Blockbench source.',
           'package dev.soulcatcherplus.client.model;', '',
           'import dev.soulcatcherplus.client.model.SoulShamanModel.Material;',
           'import java.util.LinkedHashMap;', 'import java.util.Map;', '',
           'final class SoulShamanGeometry {', '    private SoulShamanGeometry() {}', '',
           '    static Map<String, CuboidModelPart<Material>> create() {',
           '        Map<String, CuboidModelPart<Material>> parts = new LinkedHashMap<>();']
    exported_faces=0

    def part(name,origin,rotation,parent,parent_origin):
        values=[origin[i]-parent_origin[i] for i in range(3)]+rotation
        lines.append(f'        CuboidModelPart<Material> {name} = new CuboidModelPart<>('
                     +', '.join(map(number,values))+');')
        if parent:
            lines.append(f'        {parent}.children.add({name});')

    def walk(node,parent=None,parent_origin=(0,0,0)):
        nonlocal exported_faces
        group=groups[node['uuid']]
        label,origin=group['name'],group['origin']
        name=identifier(label)
        part(name,origin,group.get('rotation',[0,0,0]),parent,parent_origin)
        lines.append(f'        parts.put({json.dumps(label)}, {name});')
        for child in node['children']:
            if isinstance(child,dict):
                walk(child,name,origin)
                continue
            cube=cubes[child]
            owner,pivot=name,origin
            rotation=cube.get('rotation',[0,0,0])
            if any(rotation):
                owner,pivot=identifier('cube_'+cube['name']),cube['origin']
                part(owner,pivot,rotation,name,origin)
            bounds=[cube[edge][i]-pivot[i] for edge in ('from','to') for i in range(3)]
            uv=[]
            masks={}
            for i,face_name in enumerate(FACES):
                face=cube['faces'][face_name]
                if face.get('rotation',0):
                    raise ValueError('Rotated face UVs require an explicit export rule')
                texture=textures[face['texture']]
                material=texture['name'].upper()
                masks[material]=masks.get(material,0)|(1<<i)
                width,height=texture['uv_width'],texture['uv_height']
                uv.extend(v/(width if j%2==0 else height) for j,v in enumerate(face['uv']))
            assert sum(mask.bit_count() for mask in masks.values())==6
            assert sum(masks.values())==63
            lines.append('        // '+cube['name'])
            array='new float[] {'+', '.join(map(number,uv))+'}'
            if len(masks)>1:
                variable=identifier('uv_'+cube['name'])
                lines.append(f'        float[] {variable} = {array};')
                array=variable
            for material,mask in masks.items():
                suffix='' if mask==63 else ', '+str(mask)
                lines.append(f'        {owner}.cube(Material.{material}, '+', '.join(map(number,bounds))
                             +', '+array+suffix+');')
                exported_faces+=mask.bit_count()

    walk(model['outliner'][0])
    assert exported_faces==len(cubes)*6
    lines+=['        return parts;', '    }', '}', '']
    OUTPUT.write_text('\n'.join(lines),encoding='utf-8')
    TEXTURES.mkdir(parents=True,exist_ok=True)
    for texture in textures.values():
        header,data=texture['source'].split(',',1)
        if header!='data:image/png;base64':
            raise ValueError('Expected embedded PNG materials')
        (TEXTURES/(texture['name']+'.png')).write_bytes(base64.b64decode(data,validate=True))
    print(f'Exported {len(cubes)} cuboids, {exported_faces} faces, {len(textures)} textures.')


if __name__=='__main__':
    main()
